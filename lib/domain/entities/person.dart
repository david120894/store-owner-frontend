class Person {
  final int id;
  final String firstName;
  final String lastName;
  final String email;
  final String dni;
  final String phone;
  final String address;
  final String city;

  Person({
    required this.id,
    required this.firstName,
    required this.lastName,
    required this.email,
    required this.dni,
    required this.phone,
    required this.address,
    required this.city,
  });
}
